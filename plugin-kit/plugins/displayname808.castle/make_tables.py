#!/usr/bin/env python3
"""Writes castle_tables.h: the two tables castle takes from the Lode port (displayname808.lode's make_tables.py), with
the same values. Run: python3 make_tables.py > castle_tables.h

  SINE     1025 x Q15     one cycle of sine (+1 guard): the phase-modulation operators' "cycle"
  DETRATIO 769  x Q15     2^(s/12) - 1 for s = i/64 semitones, 0..12 (the detune's semitone mode)
"""
import math


def rows(vals, per=12):
    return "\n".join("    " + ", ".join(str(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per))


sine = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
detr = [min(round((2 ** (i / 64 / 12) - 1) * 32768), 65535) for i in range(769)]
print("/* Generated by make_tables.py: do not edit. */")
print("#ifndef CASTLE_TABLES_H\n#define CASTLE_TABLES_H\n")
print("static const short SINE[1025] = {\n" + rows(sine) + "\n};\n")
print("static const unsigned short DETRATIO[769] = {\n" + rows(detr) + "\n};\n")
print("#endif")
