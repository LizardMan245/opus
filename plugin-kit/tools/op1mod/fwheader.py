"""The firmware functions a mod can call by name: atlas/functions.csv -> op1fw.h.

Each row of atlas/functions.csv is a firmware function the atlas has verified (docs/PLAN.md
Phase 3, "Libraries"): its address, its C declaration and the facts that prove it.  The
header makes each one a typed pointer to its address, which is how the mods have always
called the firmware (arguments in R0-R2, the rest on the stack from [SP + 12]; GCC passes
them the way the firmware's own calls do, atlas F0064):

    #include "op1fw.h"
    void *h = fw_bind(page, name, 0);

A row is refused unless its name is fw_ plus lower case, its address lies in OS code (a
`code` row of atlas/space-map.csv), every fact it names exists and none is refuted, and at
least one is high confidence (two methods agree, or the device confirmed it).  `op1mod
build` writes the header next to the objects on every build, so it always matches the atlas;
`op1mod header` shows it; `op1mod header --watch-args` prints the op1emu options that log
every real call of every row (emu/core/callwatch.h), which is how a row is checked.
"""
import csv
import os
import re
import textwrap

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
FUNCTIONS = os.path.join(REPO, 'atlas', 'functions.csv')
FACTS = os.path.join(REPO, 'atlas', 'facts.csv')
SPACE_MAP = os.path.join(REPO, 'atlas', 'space-map.csv')
COLUMNS = ['name', 'address', 'returns', 'params', 'firmware', 'facts', 'notes']
NAME = re.compile(r'fw_[a-z][a-z0-9_]*$')
ADDRESS = re.compile(r'0x[0-9A-Fa-f]{8}$')
CTYPE = re.compile(r'[A-Za-z0-9_ *,.]+$')          # a C type or parameter list, nothing else


class HeaderError(Exception):
    pass


def _rows(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def check(functions, facts, code):
    """-> a list of problems (empty = every row may go into the header).  functions: rows of
    functions.csv; facts: {id: confidence}; code: [(lo, hi)] of OS code."""
    problems, names, addrs = [], set(), set()
    for i, r in enumerate(functions, 2):
        where = f'functions.csv line {i} ({r.get("name") or "?"})'
        if list(r) != COLUMNS:
            problems.append(f'{where}: columns must be {",".join(COLUMNS)}')
            continue
        if not NAME.match(r['name']):
            problems.append(f'{where}: the name must be fw_ and lower case, digits, _')
        elif r['name'] in names:
            problems.append(f'{where}: {r["name"]} appears twice')
        names.add(r['name'])
        if not ADDRESS.match(r['address']):
            problems.append(f'{where}: the address must be 0x and eight hex digits')
        else:
            a = int(r['address'], 16)
            if a in addrs:
                problems.append(f'{where}: {r["address"]} appears twice')
            addrs.add(a)
            if not any(lo <= a < hi for lo, hi in code):
                problems.append(f'{where}: {r["address"]} is not in OS code (atlas/space-map.csv)')
        for col in ('returns', 'params'):
            if not CTYPE.match(r[col]):
                problems.append(f'{where}: {col} {r[col]!r} is not a plain C type list (use void for none)')
        ids = r['facts'].split()
        if not ids:
            problems.append(f'{where}: no fact proves it')
        missing = [x for x in ids if x not in facts]
        if missing:
            problems.append(f'{where}: no such fact {", ".join(missing)}')
        if any(facts.get(x) == 'refuted' for x in ids):
            problems.append(f'{where}: a refuted fact')
        if ids and not missing and not any(facts[x] == 'high' for x in ids):
            problems.append(f'{where}: none of {", ".join(ids)} is high confidence')
    return problems


def _comment(r, facts):
    proof = ', '.join(f'{x} ({facts[x]})' for x in r['facts'].split())
    text = f'{r["name"]}: {r["firmware"]}, {r["address"]}.  {proof}.  {r["notes"]}'.strip()
    lines = textwrap.wrap(text, 92)
    return '/* ' + '\n * '.join(lines) + ' */'


def generate(functions=FUNCTIONS, facts=FACTS, space_map=SPACE_MAP, plugin=False):
    """-> the header's text; HeaderError lists every refused row. plugin: Opus 2's plugin header, each
    function declared by name with no address (the core supplies it at load: imports by name,
    docs/design/opus2-contract.md §4)."""
    rows = _rows(functions)
    conf = {r['id']: r['confidence'] for r in _rows(facts)}
    code = [(int(r['lo'], 16), int(r['hi'], 16)) for r in _rows(space_map) if r['kind'] == 'code']
    problems = check(rows, conf, code)
    if problems:
        raise HeaderError('atlas/functions.csv:\n  ' + '\n  '.join(problems))
    out = ['/* op1fw.h: the OP-1 firmware (#246) functions a mod can call by name.',
           ' * Generated by tools/op1mod/fwheader.py from atlas/functions.csv: do not edit.  To add a',
           ' * function, add a row there with the facts that prove it.  Each name is a typed pointer to',
           " * the function's address: arguments go in R0-R2, the rest on the stack from [SP + 12], as",
           ' * GCC passes them (atlas F0064). */',
           '#ifndef OP1FW_H', '#define OP1FW_H', '']
    if plugin:
        out[0:5] = ['/* op1fw.h for an Opus 2 plugin: the OP-1 firmware (#246) functions a plugin can call by name.',
                    ' * Generated by tools/op1mod/fwheader.py from atlas/functions.csv: do not edit.  Each is',
                    ' * declared by name only: the plugin imports it, the core gives its address at load',
                    ' * (docs/design/opus2-contract.md §4, the deep names). Arguments go in R0-R2, the rest on',
                    ' * the stack from [SP + 12], as GCC passes them (atlas F0064). */']
    for r in rows:
        sep = '' if r['returns'].endswith('*') else ' '
        out += [_comment(r, conf),
                f'typedef {r["returns"]}{sep}{r["name"]}_t({r["params"]});',
                f'extern {r["name"]}_t {r["name"]};' if plugin else
                f'#define {r["name"]} (({r["name"]}_t *){r["address"]})', '']
    out += ['#endif', '']
    return '\n'.join(out)


def watch_args(functions=FUNCTIONS, variadic_extra=2):
    """-> op1emu arguments that watch every function of the table (emu/core/callwatch.h):
    --watch-call ADDR:NAME:N, N = the parameters past the third (they are on the stack), plus
    `variadic_extra` words for a `...`.  How a row is checked against real calls."""
    out = []
    for r in _rows(functions):
        params = [p.strip() for p in r['params'].split(',') if p.strip() and p.strip() != 'void']
        fixed = [p for p in params if p != '...']
        n = max(0, len(fixed) - 3) + (variadic_extra if '...' in params else 0)
        out += ['--watch-call', f'{r["address"]}:{r["name"]}:{n}']
    return out


def names(functions=FUNCTIONS):
    """-> [(name, address)]: every function of the table, for the core's list of deep names."""
    return [(r['name'], int(r['address'], 16)) for r in _rows(functions)]


def write(path, **kw):
    text = generate(**kw)
    with open(path, 'w', newline='\n', encoding='utf-8') as f:
        f.write(text)
    return path
