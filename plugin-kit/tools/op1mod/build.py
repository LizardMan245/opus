"""Build a mod's payload with the native Windows Blackfin toolchain (tools/toolchain).

A mod directory holds C (*.c) and assembly (*.s, *.S) sources and a linker script link.ld
that places them at the mod's address, and optionally VERSION (the mod's version on its first
line, e.g. "1", and its build on an optional second line, e.g. "25": shown on the device so the
owner can tell which build is flashed).  build() writes op1fw.h (the firmware functions a mod can
call by name, generated by fwheader.py) and mod_version.h (MOD_VERSION and
MOD_BUILD, the two lines as C strings; "" where missing) next to the objects, compiles and
assembles each source with that directory on the include path, links them with libgcc
(division and other helpers), and writes MOD.elf, MOD.bin (the raw bytes for the LDR block),
MOD.lst (disassembly and contents) and MOD.map.
"""
import os
import shutil
import subprocess

from fwheader import HeaderError, names as fw_names, write as write_header

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
DEFAULT_TOOLCHAIN = os.path.normpath(os.path.join(REPO, '..', 'bfin-toolchain'))
# The OP-1 is an ADSP-BF524; -mcpu picks its instruction set and the workarounds for known
# silicon bugs (anomalies).  Plain bf524 means revision 0.2; the device's revision is not
# verified yet, so `-any` enables the workarounds for every revision (safe, slightly slower).
CPU = '-mcpu=bf524-any'
CFLAGS = [CPU, '-O2', '-ffreestanding', '-fno-builtin', '-Wall', '-Wextra', '-Werror']


class BuildError(Exception):
    pass


def write_names(path):
    """op1fw_names.inc: `{ "fw_name", 0xADDRESS },` per firmware function, sorted by name: Opus 2's core
    includes it as its list of deep names, which plugins import by name."""
    with open(path, 'w', newline='\n') as f:
        f.write('/* Generated by tools/op1mod/build.py from the function table (fwheader.py): the deep names. */\n')
        for name, addr in sorted(fw_names()):
            f.write(f'{{ "{name}", 0x{addr:08X}u }},\n')


def toolchain(path=None):
    """Directory holding bin/bfin-elf-*: argument, $OP1_BFIN_TOOLCHAIN, ../bfin-toolchain, or the one on the PATH
    (Linux and macOS too: the authors' kit)."""
    tc = path or os.environ.get('OP1_BFIN_TOOLCHAIN') or DEFAULT_TOOLCHAIN
    if not os.path.exists(tool(tc, 'gcc')) and not path and not os.environ.get('OP1_BFIN_TOOLCHAIN'):
        found = shutil.which('bfin-elf-gcc')
        if found:
            tc = os.path.dirname(os.path.dirname(os.path.realpath(found)))
    if not os.path.exists(tool(tc, 'gcc')):
        raise BuildError(f'no Blackfin toolchain at {tc}: build it with tools/toolchain/build-bfin-toolchain.sh')
    return tc


def tool(tc, name):
    return os.path.join(tc, 'bin', f'bfin-elf-{name}' + ('.exe' if os.name == 'nt' else ''))


def run(cmd, out_path=None):
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise BuildError(f'{os.path.basename(cmd[0])} failed:\n{p.stdout}{p.stderr}')
    if out_path:
        with open(out_path, 'w', newline='\n') as f:
            f.write(p.stdout)
    return p.stdout


def read_version(mod_dir):
    """(version, build) from mod_dir/VERSION: its first line and its optional second ('' where
    missing); each 1-15 printable characters, no quotes or backslashes (they become C strings)."""
    path = os.path.join(mod_dir, 'VERSION')
    if not os.path.exists(path):
        return '', ''
    with open(path, encoding='ascii', errors='replace') as f:
        lines = [l.strip() for l in f.read().splitlines()]
    out = []
    for i, v in enumerate((lines + ['', ''])[:2]):
        if i == 1 and not v:
            out.append('')
            continue
        if not 1 <= len(v) <= 15 or any(c in '"\\' or not ' ' <= c <= '~' for c in v):
            raise BuildError(f'{path} line {i + 1}: expected 1-15 printable characters, no quotes or backslashes, got {v!r}')
        out.append(v)
    return out[0], out[1]


def read_dev(mod_dir):
    """The dev build number in mod_dir/DEV (one line, a number), or None without the file. `op1mod apply`
    without --release counts it up: each dev build made for the device shows its own number."""
    path = os.path.join(mod_dir, 'DEV')
    if not os.path.exists(path):
        return None
    with open(path, encoding='ascii', errors='replace') as f:
        v = f.read().strip()
    if not v.isdigit() or len(v) > 6:
        raise BuildError(f'{path}: expected a number, got {v!r}')
    return int(v)


L1_BASE = 0xFF800000                       # L1 memory: sections linked here are not in the payload


def build(mod_dir, out_dir, tc=None, hits=None, defines=()):
    """-> dict(elf, bin, lst, map, size, symbols, l1, zero, hits) for the mod in mod_dir.  l1: {section
    name: (VMA, bytes)} for the sections linked into L1 (link.ld, e.g. .l1code at 0xFFA040C8 for an
    `l1code` hook): they are cut out of the payload, which holds SDRAM only, and placed by their hooks.
    hits: the places that may be counted (hits.candidates); those whose symbol is code get a counter
    and a stub (hits.source), and `hits` in the result is [(place address, stub symbol, label)].
    defines: names given to every C and .S source (-D; the release build's OPUS_RELEASE)."""
    tc = toolchain(tc)
    name = os.path.basename(os.path.normpath(mod_dir))
    ld_script = os.path.join(mod_dir, 'link.ld')
    if not os.path.exists(ld_script):
        raise BuildError(f'{mod_dir} has no link.ld')
    # Exact, case-sensitive extensions: on Windows the patterns *.s and *.S match the same files.
    sources = sorted(os.path.join(mod_dir, f) for f in os.listdir(mod_dir)
                     if os.path.splitext(f)[1] in ('.c', '.s', '.S'))
    if not sources:
        raise BuildError(f'{mod_dir} has no .c, .s or .S sources')
    os.makedirs(out_dir, exist_ok=True)
    try:
        write_header(os.path.join(out_dir, 'op1fw.h'))
        write_names(os.path.join(out_dir, 'op1fw_names.inc'))
    except HeaderError as e:
        raise BuildError(str(e))
    version, build_no = read_version(mod_dir)
    dev = read_dev(mod_dir)
    with open(os.path.join(out_dir, 'mod_version.h'), 'w', newline='\n') as f:
        f.write(f'/* Generated by op1mod build from VERSION and DEV. */\n#define MOD_VERSION "{version}"\n'
                f'#define MOD_BUILD "{build_no}"\n' + (f'#define MOD_DEV "{dev}"\n' if dev is not None else ''))
    objs = []
    for src in sources:
        obj = os.path.join(out_dir, os.path.splitext(os.path.basename(src))[0] + '.o')
        if src.endswith('.s'):
            run([tool(tc, 'as'), CPU, '-o', obj, src])
        else:
            run([tool(tc, 'gcc')] + CFLAGS + ['-D' + d for d in defines] + ['-I', out_dir, '-c', '-o', obj, src])
        objs.append(obj)
    stubs = []
    if hits is not None:                   # the hit counters (hits.py): stubs for the places whose symbol is code
        from hits import code_symbols, source
        code = {}
        for obj in objs:
            code.update(code_symbols(run([tool(tc, 'objdump'), '-t', obj]).splitlines()))
        text, stubs = source(hits, code)
        src = os.path.join(out_dir, '_hits.s')
        with open(src, 'w', newline='\n') as f:
            f.write(text)
        obj = os.path.join(out_dir, '_hits.o')
        run([tool(tc, 'as'), CPU, '-o', obj, src])
        objs.append(obj)
    elf = os.path.join(out_dir, name + '.elf')
    mapf = os.path.join(out_dir, name + '.map')
    run([tool(tc, 'gcc'), CPU, '-nostdlib', '-T', ld_script, '-Wl,-Map=' + mapf, '-o', elf] + objs + ['-lgcc'])
    binf = os.path.join(out_dir, name + '.bin')
    # The sections linked into L1 (an ALLOC section whose VMA is at or above 0xFF800000).
    lines = run([tool(tc, 'objdump'), '-h', elf]).splitlines()
    l1_names = []
    for head, flags in zip(lines, lines[1:]):
        f = head.split()
        if len(f) == 7 and f[0].isdigit() and 'ALLOC' in flags and int(f[3], 16) >= L1_BASE and int(f[2], 16):
            l1_names.append((f[1], int(f[3], 16)))
    cut = [a for n, _ in l1_names for a in ('-R', n)]
    # .bss (zero-initialised globals) is not stored in an ELF file, and SDRAM there is not
    # zeroed by anyone else.  The payload holds what has contents (to .data's end); the zeros
    # after it, to .bss's end, are one FILL block (`zero`: (address, bytes)), which the loader
    # writes as stock's own zeroed memory: 16 bytes in the LDR, not the zeros
    # themselves (build 67: Opus's 664,176; maiko's #248 does the same for its RAM).
    run([tool(tc, 'objcopy'), '-O', 'binary'] + cut + [elf, binf])
    l1 = {}
    for n, vma in l1_names:
        part = os.path.join(out_dir, f'{name}{n.replace(".", "_")}.bin')
        run([tool(tc, 'objcopy'), '-O', 'binary', '-j', n, elf, part])
        with open(part, 'rb') as f:
            l1[n] = (vma, f.read())
    lst = os.path.join(out_dir, name + '.lst')
    run([tool(tc, 'objdump'), '-d', '-s', elf], lst)
    syms = []
    for line in run([tool(tc, 'nm'), '-n', elf]).splitlines():
        f = line.split()
        if len(f) == 3:
            syms.append((int(f[0], 16), f[1], f[2]))
    # The payload starts at the lowest address of any allocated section outside L1 (objdump -h: a
    # line "Idx Name Size VMA LMA Off Algn", then its flags).
    vmas = []
    for head, flags in zip(lines, lines[1:]):
        f = head.split()
        if len(f) == 7 and f[0].isdigit() and 'ALLOC' in flags and int(f[2], 16) and int(f[3], 16) < L1_BASE:
            vmas.append(int(f[3], 16))
    if not vmas:
        raise BuildError(f'{elf}: no allocated section')
    load, size = min(vmas), os.path.getsize(binf)
    # The zero fill: from the payload's end to the end of the last zeroed section below L1 that
    # is loaded (.bss and COMMON; NOLOAD sections such as Opus's .far are cleared by the mod).
    end = load + size
    for head, flags in zip(lines, lines[1:]):
        f = head.split()
        if (len(f) == 7 and f[0].isdigit() and 'ALLOC' in flags and 'LOAD' not in flags and int(f[2], 16)
                and load <= int(f[3], 16) < L1_BASE and f[1] in ('.bss', 'COMMON', '.sbss')):
            end = max(end, int(f[3], 16) + int(f[2], 16))
    end = (end + 3) & ~3
    zero = (load + size, end - load - size) if end > load + size else None
    if zero and size % 4:
        raise BuildError(f'{elf}: the payload ends at 0x{load + size:08x}, not on a word: the zero fill must start on one')
    return dict(elf=elf, bin=binf, lst=lst, map=mapf, size=size, symbols=syms, load=load, l1=l1, zero=zero,
                hits=stubs)
